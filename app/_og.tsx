// Shared Open Graph card used by `opengraph-image` routes.
//
// The card is set in PP Kyoto when the licensed fonts were downloaded at
// build time (see scripts/fetch-fonts.mjs): the description as a quotation, a
// bold title, and a series line like "Shu Ding, Thoughts". Without them, as in
// forks, it falls back to the open-source card below.

import { existsSync, readFileSync } from 'fs'
import path from 'path'

export const ogSize = { width: 1200, height: 630 }

// Each helper is scoped to one folder, so file tracing stays scoped too.
const siteFont = (file: string) =>
  readFileSync(path.join(process.cwd(), 'app', '_fonts', file))
const kyotoPath = (name: string) =>
  path.join(process.cwd(), 'public', 'fonts', 'kyoto', `kyoto-og-${name}.otf`)

const hasKyoto = ['regular', 'italic', 'bold'].every((name) =>
  existsSync(kyotoPath(name)),
)

const inter = {
  name: 'Inter',
  data: siteFont('Inter-Medium.ttf'),
  style: 'normal' as const,
  weight: 600 as const,
}

export const ogFonts = hasKyoto
  ? [
      inter,
      ...(
        [
          ['regular', 400, 'normal'],
          ['italic', 400, 'italic'],
          ['bold', 700, 'normal'],
        ] as const
      ).map(([name, weight, style]) => ({
        name: 'Kyoto',
        data: readFileSync(kyotoPath(name)),
        weight,
        style,
      })),
    ]
  : [
      inter,
      {
        name: 'GeistPixel-Square',
        data: siteFont('GeistPixel-Square.ttf'),
        style: 'normal' as const,
        weight: 600 as const,
      },
      // Static Lora Italic generated by `scripts/subset-fonts.py`.
      {
        name: 'Serif',
        data: siteFont('og/lora-italic-500.ttf'),
        style: 'italic' as const,
        weight: 500 as const,
      },
    ]

type OgCardProps = {
  title: string
  description?: string
  // The series line under the title: "<author>, <collection>". Either part
  // can be left out.
  author?: string
  collection?: string
  // The fallback card ends article titles with an arrow.
  arrow?: boolean
}

export function OgCard(props: OgCardProps) {
  return hasKyoto ? <KyotoCard {...props} /> : <FallbackCard {...props} />
}

const INK = '#1e2125'
const QUOTE = '#697381'
const MARK = '#c3c8ce'
const QUIET = '#8c95a1'
const QUOTE_SIZE = 34

// Larger titles for shorter text; lines are balanced either way.
function titleSize(title: string) {
  if (title.length <= 16) return 120
  if (title.length <= 32) return 96
  return 76
}

function KyotoCard({ title, description, author, collection }: OgCardProps) {
  // The card adds its own hanging quotation mark.
  const quote = description?.replace(/^[“"]|[”"]$/g, '')
  const size = titleSize(title)

  return (
    <div
      style={{
        width: '100%',
        height: '100%',
        display: 'flex',
        flexDirection: 'column',
        padding: '84px 104px 72px',
        background: '#fcfcfc',
        fontFamily: 'Kyoto',
      }}
    >
      {quote ? (
        <div style={{ display: 'flex', position: 'relative', maxWidth: 900 }}>
          <div
            style={{
              position: 'absolute',
              left: -QUOTE_SIZE * 0.58,
              top: 0,
              fontSize: QUOTE_SIZE,
              lineHeight: 1.45,
              color: MARK,
            }}
          >
            “
          </div>
          {/* At most three lines, so long descriptions leave room for the
              title. */}
          <div
            style={{
              display: 'block',
              fontSize: QUOTE_SIZE,
              lineHeight: 1.45,
              color: QUOTE,
              textWrap: 'pretty',
              lineClamp: 3,
            }}
          >
            {quote}
          </div>
        </div>
      ) : null}
      <div
        style={{
          marginTop: 'auto',
          paddingTop: 32,
          flexShrink: 0,
          fontSize: size,
          fontWeight: 700,
          lineHeight: 1.04,
          letterSpacing: size * -0.025,
          color: INK,
          maxWidth: 1000,
          textWrap: 'balance',
        }}
      >
        {title}
      </div>
      {author || collection ? (
        <div
          style={{
            display: 'flex',
            marginTop: 36,
            fontSize: 30,
            lineHeight: 1,
            color: '#4a515b',
          }}
        >
          {author ? (
            <span style={{ fontWeight: 700, letterSpacing: -0.3 }}>
              {author}
            </span>
          ) : null}
          {author && collection ? (
            <span style={{ color: QUIET, whiteSpace: 'pre' }}>, </span>
          ) : null}
          {collection ? (
            <span style={{ color: QUIET, fontStyle: 'italic' }}>
              {collection}
            </span>
          ) : null}
        </div>
      ) : null}
    </div>
  )
}

// The open-source card, used without the licensed fonts.
function FallbackCard({ title, description, arrow }: OgCardProps) {
  return (
    <div
      style={{
        width: '100%',
        height: '100%',
        display: 'flex',
        flexDirection: 'column',
        justifyContent: 'flex-start',
        padding: '60px 80px 80px',
        background: '#f5f7fa',
        fontFamily: 'Inter',
      }}
    >
      <div
        style={{
          fontSize: 82,
          fontWeight: 500,
          fontStyle: 'italic',
          color: '#0e0f11',
          lineHeight: 1.3,
          maxWidth: 1000,
          textWrap: 'pretty',
          letterSpacing: -0.6,
          fontFamily: 'Serif',
          marginLeft: -2,
        }}
      >
        {arrow ? `${title} →` : title}
      </div>
      {description ? (
        <div
          style={{
            fontSize: 42,
            color: '#4a515b',
            marginTop: 36,
            maxWidth: 900,
            lineHeight: 1.5,
            letterSpacing: -0.2,
            fontFamily: 'Inter',
          }}
        >
          {description}
        </div>
      ) : null}
    </div>
  )
}
